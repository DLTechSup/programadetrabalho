const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("api", {
  abrirArquivo: () => ipcRenderer.invoke("arquivo:abrir"),
  salvarArquivo: (nomeSugerido, dados) => ipcRenderer.invoke("arquivo:salvar", nomeSugerido, dados),
  carregarCores: () => ipcRenderer.invoke("cores:carregar"),
  salvarCores: (json) => ipcRenderer.invoke("cores:salvar", json),
  caminhoCores: () => ipcRenderer.invoke("cores:caminho"),
  exportarCores: (json) => ipcRenderer.invoke("cores:exportar", json),
  importarCores: () => ipcRenderer.invoke("cores:importar"),
  mostrarNaPasta: (caminho) => ipcRenderer.invoke("shell:mostrar", caminho),
  escolherPasta: () => ipcRenderer.invoke("scan:escolher"),
  lerDaPasta: (caminho) => ipcRenderer.invoke("scan:ler", caminho),
  versao: () => ipcRenderer.invoke("app:versao"),
  // ---- Renomeador em Massa ----
  escolherArquivosParaRenomear: () => ipcRenderer.invoke("renomear:escolherArquivos"),
  listarPasta: (pasta) => ipcRenderer.invoke("renomear:listarPasta", pasta),
  renomearExecutar: (pares) => ipcRenderer.invoke("renomear:executar", pares),
  renomearDesfazer: (feitos) => ipcRenderer.invoke("renomear:desfazer", feitos),
  // ---- Captura de Tela ----
  capturaConfigCarregar: () => ipcRenderer.invoke("captura:configCarregar"),
  capturaConfigSalvar: (novo) => ipcRenderer.invoke("captura:configSalvar", novo),
  capturaEscolherPasta: () => ipcRenderer.invoke("captura:escolherPasta"),
  capturaAbrirPasta: (pasta) => ipcRenderer.invoke("captura:abrirPasta", pasta),
  // ---- Monitor de Demandas ----
  monitorConfigCarregar: () => ipcRenderer.invoke("monitor:configCarregar"),
  monitorConfigSalvar: (novo) => ipcRenderer.invoke("monitor:configSalvar", novo),
  monitorEscolherPasta: () => ipcRenderer.invoke("monitor:escolherPasta"),
  monitorIniciar: () => ipcRenderer.invoke("monitor:iniciar"),
  monitorParar: () => ipcRenderer.invoke("monitor:parar"),
  monitorEstado: () => ipcRenderer.invoke("monitor:estado"),
  monitorListaDoDia: (grupo) => ipcRenderer.invoke("monitor:listaDoDia", grupo),
  monitorMarcarFeito: (grupo, chave, feito) => ipcRenderer.invoke("monitor:marcarFeito", grupo, chave, feito),
  monitorLogDeHoje: () => ipcRenderer.invoke("monitor:logDeHoje"),
  monitorAbrirPastaDoDia: (grupo) => ipcRenderer.invoke("monitor:abrirPastaDoDia", grupo),
  aoMudarLogMonitor: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("monitor:log", h); return () => ipcRenderer.removeListener("monitor:log", h); },
  aoMudarListaMonitor: (cb) => { const h = () => cb(); ipcRenderer.on("monitor:listaMudou", h); return () => ipcRenderer.removeListener("monitor:listaMudou", h); },
  aoSalvarMonitor: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("monitor:salvo", h); return () => ipcRenderer.removeListener("monitor:salvo", h); },
  aoMudarEstadoMonitor: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("monitor:estado", h); return () => ipcRenderer.removeListener("monitor:estado", h); },
  // ---- NoteDeck ----
  listNotes: () => ipcRenderer.invoke("notes:list"),
  getNote: (id) => ipcRenderer.invoke("notes:get", id),
  createNote: (opts) => ipcRenderer.invoke("notes:create", opts),
  updateNote: (id, patch) => ipcRenderer.invoke("notes:update", id, patch),
  setVisible: (id, v) => ipcRenderer.invoke("notes:setVisible", id, v),
  setAllVisible: (v) => ipcRenderer.invoke("notes:setAllVisible", v),
  duplicateNote: (id) => ipcRenderer.invoke("notes:duplicate", id),
  trashNote: (id) => ipcRenderer.invoke("notes:trash", id),
  restoreNote: (id) => ipcRenderer.invoke("notes:restore", id),
  deleteNote: (id) => ipcRenderer.invoke("notes:delete", id),
  emptyTrash: () => ipcRenderer.invoke("notes:emptyTrash"),
  exportNoteTxt: (id) => ipcRenderer.invoke("notes:exportTxt", id),
  focusNote: (id) => ipcRenderer.invoke("notes:focus", id),
  exportBackup: () => ipcRenderer.invoke("backup:export"),
  importBackup: () => ipcRenderer.invoke("backup:import"),
  importDb: () => ipcRenderer.invoke("backup:importDb"),
  backupNow: () => ipcRenderer.invoke("backup:now"),
  pickBackupDir: () => ipcRenderer.invoke("backup:pickDir"),
  openBackupDir: () => ipcRenderer.invoke("backup:openDir"),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (p) => ipcRenderer.invoke("settings:set", p),
  getInfo: () => ipcRenderer.invoke("app:info"),
  dragStart: () => ipcRenderer.send("win:dragStart"),
  dragMove: (noSnap) => ipcRenderer.send("win:dragMove", !!noSnap),
  dragEnd: () => ipcRenderer.send("win:dragEnd"),
  onEditorCommand: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("editor:cmd", h); return () => ipcRenderer.removeListener("editor:cmd", h); },
  winControl: (action) => ipcRenderer.invoke("win:control", action),
  openManager: () => ipcRenderer.invoke("app:openManager"),
  quit: () => ipcRenderer.invoke("app:quit"),
  onNotesChanged: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("notes:changed", h); return () => ipcRenderer.removeListener("notes:changed", h); },
  onNoteUpdated: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("note:updated", h); return () => ipcRenderer.removeListener("note:updated", h); },
  onSettingsChanged: (cb) => { const h = (_e, d) => cb(d); ipcRenderer.on("settings:changed", h); return () => ipcRenderer.removeListener("settings:changed", h); },
  aoAbrirFerramenta: (cb) => {
    const ouvinte = (_e, id, arquivos) => cb(id, arquivos);
    ipcRenderer.on("ferramenta:abrir", ouvinte);
    return () => ipcRenderer.removeListener("ferramenta:abrir", ouvinte);
  },
});
